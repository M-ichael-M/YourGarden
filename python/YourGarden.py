app = Flask(__name__)

DOWNLOAD_DIR = os.path.abspath("downloads")

ydl_opts = {
    'format': 'bestaudio/best',
    'outtmpl': os.path.join(DOWNLOAD_DIR, '%(title)s.%(ext)s'),
    'noplaylist': True,
    'ffmpeg_location': os.path.abspath("bin/ffmpeg.exe")
}


def download_song(url):
    if not os.path.exists(DOWNLOAD_DIR):
        os.makedirs(DOWNLOAD_DIR)
    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        info = ydl.extract_info(url, download=True)
        filename = ydl.prepare_filename(info)
        return filename


@app.route('/download', methods=['POST'])
def download():
    data = request.get_json()
    youtube_url = data.get('youtube_url')

    if not youtube_url:
        return {"error": "No URL provided"}, 400

    try:
        file_path = download_song(youtube_url)

        # Sprawdzamy, czy plik istnieje
        if not os.path.exists(file_path):
            return {"error": "File not found"}, 500

        response = send_file(file_path, mimetype='audio/webm', as_attachment=True)

        # Usuwamy plik po wysłaniu odpowiedzi, ale z opóźnieniem
        def delayed_delete():
            time.sleep(5)  # Dajemy czas na pobranie pliku
            if os.path.exists(file_path):
                os.remove(file_path)

        from threading import Thread
        Thread(target=delayed_delete).start()

        return response
    except Exception as e:
        return {"error": str(e)}, 500


